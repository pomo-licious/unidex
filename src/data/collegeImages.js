const normalise = value => String(value || '').normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '')

function safeImageUrl(value) {
  if (typeof value !== 'string' || !value.trim()) return null
  if (/^\/assets\/colleges\/[a-zA-Z0-9._/-]+$/.test(value) && !value.includes('..')) return value
  try {
    const url = new URL(value)
    // Commons pictures are bundled locally, never hotlinked. Stock photography
    // is not a campus substitute, even if an older database row contains it.
    if (url.protocol !== 'https:' || /(^|\.)(wikimedia\.org|unsplash\.com|pexels\.com|pixabay\.com)$/.test(url.hostname)) return null
    return url.href
  } catch { return null }
}

export function getCollegeImage(college) {
  if (!college) return null
  const name = normalise(college.name)
  const bundled = COLLEGE_IMAGES.find(image => image.ids?.includes(college.id) || image.names?.some(alias => normalise(alias) === name))
  if (bundled && safeImageUrl(bundled.src)) return { ...bundled, src: safeImageUrl(bundled.src), smallSrc: safeImageUrl(bundled.smallSrc) }
  const existing = safeImageUrl(college.image_url)
  if (!existing) return null
  return {
    src: existing,
    alt: `${college.name || 'Institution'} campus`,
    credit: college.image_credit || '',
    license: college.image_license || '',
    sourceUrl: college.image_source_url || '',
    licenseUrl: college.image_license_url || '',
    objectPosition: '50% 50%',
  }
}
